pub(crate) fn measure_text(text: &str, size: f32, font: PdfFont) -> f32 {
    text.chars()
        .map(|ch| glyph_width(ch, font) as f32 * size / 1000.0)
        .sum()
}

fn glyph_width(ch: char, font: PdfFont) -> u16 {
    if font == PdfFont::Courier {
        return 600;
    }
    let normalized = metric_character(ch);
    if (' '..='~').contains(&normalized) {
        let widths = match font {
            PdfFont::Helvetica | PdfFont::HelveticaOblique => &HELVETICA,
            PdfFont::HelveticaBold => &HELVETICA_BOLD,
            PdfFont::TimesRoman => &TIMES_ROMAN,
            PdfFont::TimesBold => &TIMES_BOLD,
            PdfFont::TimesItalic => &TIMES_ITALIC,
            PdfFont::Courier => unreachable!(),
        };
        return widths[normalized as usize - 32];
    }
    match ch {
        '\u{2013}' => 556,
        '\u{2014}' => 1000,
        '\u{2026}' => 1000,
        _ => 600,
    }
}

fn metric_character(ch: char) -> char {
    match ch {
        '\u{2018}' | '\u{2019}' | '\u{201A}' | '\u{2032}' => '\'',
        '\u{201C}' | '\u{201D}' | '\u{201E}' | '\u{2033}' => '"',
        '\u{00A0}' | '\u{2007}' | '\u{202F}' => ' ',
        'À' | 'Á' | 'Â' | 'Ã' | 'Ä' | 'Å' => 'A',
        'à' | 'á' | 'â' | 'ã' | 'ä' | 'å' => 'a',
        'Ç' => 'C',
        'ç' => 'c',
        'È' | 'É' | 'Ê' | 'Ë' => 'E',
        'è' | 'é' | 'ê' | 'ë' => 'e',
        'Ì' | 'Í' | 'Î' | 'Ï' => 'I',
        'ì' | 'í' | 'î' | 'ï' => 'i',
        'Ñ' => 'N',
        'ñ' => 'n',
        'Ò' | 'Ó' | 'Ô' | 'Õ' | 'Ö' | 'Ø' => 'O',
        'ò' | 'ó' | 'ô' | 'õ' | 'ö' | 'ø' => 'o',
        'Ù' | 'Ú' | 'Û' | 'Ü' => 'U',
        'ù' | 'ú' | 'û' | 'ü' => 'u',
        'Ý' => 'Y',
        'ý' | 'ÿ' => 'y',
        other => other,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn uses_real_base14_widths_per_style() {
        assert!(measure_text("WWW", 12.0, PdfFont::Helvetica)
            > measure_text("iii", 12.0, PdfFont::Helvetica));
        assert_ne!(
            measure_text("mixed", 12.0, PdfFont::Helvetica),
            measure_text("mixed", 12.0, PdfFont::HelveticaBold)
        );
    }

    #[test]
    fn western_unicode_has_stable_fallback_metrics() {
        assert_eq!(
            measure_text("Zürich", 12.0, PdfFont::Helvetica),
            measure_text("Zurich", 12.0, PdfFont::Helvetica)
        );
    }
}
